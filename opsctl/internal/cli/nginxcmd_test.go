func TestNginxHelpIsExactAndInert(t *testing.T) {
	// R-58DF-B1B4
	for _, uid := range []int{0, 1000} {
		for _, option := range []string{"-h", "--help"} {
			called := false
			root := filepath.Join(t.TempDir(), "absent")
			stdout, stderr, code := invoke([]string{"nginx", option}, cli.Deps{
				Root: root, EUID: uid,
				Execute: func(context.Context, host.Command) (host.Result, error) {
					called = true
					return host.Result{}, errors.New("unexpected execution")
				},
			})
			if code != 0 || stdout != wantNginxUsage || stderr != "" || called {
				t.Fatalf("uid %d %s: exit %d stdout %q stderr %q executed %t", uid, option, code, stdout, stderr, called)
			}
			if _, err := os.Stat(root); !os.IsNotExist(err) {
				t.Fatalf("help changed host root: %v", err)
			}
		}
	}
}

func TestNginxGrammarPrecedesConfigurationAndHostWork(t *testing.T) {
	// R-54PQ-5Q31
	// R-FSNN-9FKB
	root := t.TempDir()
	writeCorruptCLIConfigFile(t, root)
	marker := filepath.Join(root, "marker")
	if err := os.WriteFile(marker, []byte("unchanged"), 0o600); err != nil {
		t.Fatal(err)
	}
	before := treeState(t, root)
	called := 0
	deps := cli.Deps{Root: root, EUID: 0, Execute: func(context.Context, host.Command) (host.Result, error) {
		called++
		return host.Result{}, nil
	}}
	tests := []struct {
		args []string
		want string
	}{
		{[]string{"nginx"}, "opsctl: no nginx subcommand given\n\nsee 'opsctl nginx --help' for usage\n"},
		{[]string{"nginx", "reload"}, "opsctl: unknown nginx subcommand 'reload'\n\nsee 'opsctl nginx --help' for usage\n"},
		{[]string{"nginx", "bad\r\nname"}, "opsctl: unknown nginx subcommand 'bad\\r\\nname'\n\nsee 'opsctl nginx --help' for usage\n"},
		{[]string{"nginx", "show", "extra"}, "opsctl: nginx show takes no arguments\n\nsee 'opsctl nginx --help' for usage\n"},
		{[]string{"nginx", "show", "--force"}, "opsctl: nginx show takes no arguments\n\nsee 'opsctl nginx --help' for usage\n"},
		{[]string{"nginx", "apply", "extra"}, "opsctl: nginx apply takes no arguments\n\nsee 'opsctl nginx --help' for usage\n"},
		{[]string{"nginx", "apply", "--force"}, "opsctl: nginx apply takes no arguments\n\nsee 'opsctl nginx --help' for usage\n"},
	}
	for _, test := range tests {
		stdout, stderr, code := invoke(test.args, deps)
		if code != 2 || stdout != "" || stderr != test.want {
			t.Errorf("%v: exit %d stdout %q stderr %q, want %q", test.args, code, stdout, stderr, test.want)
		}
	}
	if called != 0 || !reflect.DeepEqual(treeState(t, root), before) {
		t.Fatal("invalid invocation read configuration, executed a command, or changed host state")
	}
}

func TestNginxRequiresHostNameBeforeDomainWork(t *testing.T) {
	// R-5AT8-2KSI
	for _, command := range []string{"show", "apply"} {
		for _, configured := range []bool{false, true} {
			state := "missing"
			if configured {
				state = "empty"
			}
			t.Run(command+"/"+state, func(t *testing.T) {
				root := t.TempDir()
				if configured {
					if err := (config.Store{Root: root}).Set("host.name", ""); err != nil {
						t.Fatal(err)
					}
				}
				before := treeState(t, root)
				called := false
				stdout, stderr, code := invoke([]string{"nginx", command}, cli.Deps{Root: root, EUID: 0, Execute: func(context.Context, host.Command) (host.Result, error) {
					called = true
					return host.Result{}, nil
				}})
				if code != 1 || stdout != "" || stderr != "opsctl: host.name not set\n" || called {
					t.Fatalf("exit %d stdout %q stderr %q executed %t", code, stdout, stderr, called)
				}
				if after := treeState(t, root); !reflect.DeepEqual(after, before) {
					t.Fatalf("missing host.name changed state: before %#v after %#v", before, after)
				}
			})
		}
	}
}

