func TestNginxApplyUsesHostEnvironmentAndSuppressesSuccessOutput(t *testing.T) {
	// R-W6Y4-9GMN
	root := configuredNginxRoot(t)
	if err := os.MkdirAll(filepath.Join(root, "etc", "nginx", "conf.d"), 0o750); err != nil {
		t.Fatal(err)
	}
	writeNginxManifest(t, root, "api", "app = \"api\"\nport = 8123\n")
	var commands []host.Command
	stdout, stderr, code := invoke([]string{"nginx", "apply"}, cli.Deps{Root: root, EUID: 0, Execute: func(_ context.Context, command host.Command) (host.Result, error) {
		commands = append(commands, command)
		return host.Result{Stdout: []byte("success stdout\n"), Stderr: []byte("success stderr\n")}, nil
	}})
	wantCommands := []host.Command{{Name: "nginx", Args: []string{"-t"}}, {Name: "systemctl", Args: []string{"reload", "nginx"}}}
	if code != 0 || stdout != "" || stderr != "" || !reflect.DeepEqual(commands, wantCommands) {
		t.Fatalf("exit %d stdout %q stderr %q commands %#v", code, stdout, stderr, commands)
	}
	rootFS, err := os.OpenRoot(root)
	if err != nil {
		t.Fatal(err)
	}
	contents, err := rootFS.ReadFile("etc/nginx/conf.d/ikigenba.conf")
	closeErr := rootFS.Close()
	if err != nil {
		t.Fatal(err)
	}
	if closeErr != nil {
		t.Fatal(closeErr)
	}
	if !strings.Contains(string(contents), "api.example.test") || !strings.Contains(string(contents), "127.0.0.1:8123") {
		t.Fatalf("published configuration = %q", contents)
	}
}

func TestNginxExternalFailuresUseCommandDiagnostics(t *testing.T) {
	// R-W5Q7-VOVY
	// R-W6Y4-9GMN
	for _, test := range []struct {
		name        string
		failCommand string
		result      host.Result
		err         error
		want        string
	}{
		{name: "test", failCommand: "nginx", result: host.Result{ExitCode: 23, Stdout: []byte("bad stdout\n"), Stderr: []byte("bad stderr")}, want: "opsctl: nginx -t: exit status 23\n\n> bad stdout\n> bad stderr\n"},
		{name: "reload", failCommand: "systemctl", result: host.Result{Stdout: []byte("reload stdout"), Stderr: []byte("reload stderr\n")}, err: errors.New("cannot execute"), want: "opsctl: systemctl reload nginx: cannot execute\n\n> reload stdout\n> reload stderr\n"},
	} {
		t.Run(test.name, func(t *testing.T) {
			root := configuredNginxRoot(t)
			if err := os.MkdirAll(filepath.Join(root, "etc", "nginx", "conf.d"), 0o750); err != nil {
				t.Fatal(err)
			}
			stdout, stderr, code := invoke([]string{"nginx", "apply"}, cli.Deps{Root: root, EUID: 0, Execute: func(_ context.Context, command host.Command) (host.Result, error) {
				if command.Name == test.failCommand {
					return test.result, test.err
				}
				return host.Result{Stdout: []byte("suppressed"), Stderr: []byte("suppressed")}, nil
			}})
			if code != 1 || stdout != "" || stderr != test.want {
				t.Fatalf("exit %d stdout %q stderr %q, want %q", code, stdout, stderr, test.want)
			}
		})
	}
}

func TestNginxStandaloneRenderAndApplyFailures(t *testing.T) {
	// R-5GWP-ZFHZ
	// R-W6Y4-9GMN
	// R-G0B8-HTXJ
	// R-G1J4-VLO8
	tests := []struct {
		name    string
		command string
		setup   func(*testing.T, string)
		want    []string
	}{
		{name: "show discovery failure", command: "show", setup: func(t *testing.T, root string) {
			if err := os.WriteFile(filepath.Join(root, "opt"), []byte("not a directory"), 0o600); err != nil {
				t.Fatal(err)
			}
		}, want: []string{"discover services", "read /opt"}},
		{name: "show malformed manifest", command: "show", setup: func(t *testing.T, root string) {
			writeNginxManifest(t, root, "broken", "port = [\n")
		}, want: []string{"broken", "manifest"}},
		{name: "apply conflicting defaults", command: "apply", setup: func(t *testing.T, root string) {
			writeNginxManifest(t, root, "alpha", "app = \"alpha\"\nport = 1\ndefault = true\n")
			writeNginxManifest(t, root, "zeta", "app = \"zeta\"\nport = 2\ndefault = true\n")
		}, want: []string{"conflicting default services", "alpha", "zeta"}},
		{name: "apply preparation failure", command: "apply", want: []string{"publish nginx configuration", "no such file or directory"}},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := configuredNginxRoot(t)
			if test.setup != nil {
				test.setup(t, root)
			}
			before := treeState(t, root)
			called := false
			stdout, stderr, code := invoke([]string{"nginx", test.command}, cli.Deps{Root: root, EUID: 0, Execute: func(context.Context, host.Command) (host.Result, error) {
				called = true
				return host.Result{}, nil
			}})
			if code != 1 || stdout != "" || called {
				t.Fatalf("exit %d stdout %q stderr %q executed %t", code, stdout, stderr, called)
			}
			for _, part := range test.want {
				if !strings.Contains(stderr, part) {
					t.Errorf("stderr %q does not contain %q", stderr, part)
				}
			}
			if after := treeState(t, root); !reflect.DeepEqual(after, before) {
				t.Fatalf("failed operation changed state: before %#v after %#v", before, after)
			}
		})
	}
}

func configuredNginxRoot(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	if err := (config.Store{Root: root}).Set("host.name", "example.test"); err != nil {
		t.Fatal(err)
	}
	return root
}

func writeNginxManifest(t *testing.T, root, name, contents string) {
	t.Helper()
	directory := filepath.Join(root, "opt", name, "etc")
	if err := os.MkdirAll(directory, 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(directory, "manifest.toml"), []byte(contents), 0o600); err != nil {
		t.Fatal(err)
	}
}
