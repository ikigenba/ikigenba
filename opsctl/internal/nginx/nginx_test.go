func observeNextTemporaryConfiguration(t *testing.T, directory string, inject func(string) error) <-chan error {
	t.Helper()
	fd, err := syscall.InotifyInit1(syscall.IN_CLOEXEC)
	if err != nil {
		t.Fatalf("initialize inotify: %v", err)
	}
	if _, err := syscall.InotifyAddWatch(fd, directory, syscall.IN_CREATE); err != nil {
		_ = syscall.Close(fd)
		t.Fatalf("watch configuration directory: %v", err)
	}
	result := make(chan error, 1)
	go func() {
		defer func() { _ = syscall.Close(fd) }()
		buffer := make([]byte, syscall.SizeofInotifyEvent+256)
		for {
			count, readErr := syscall.Read(fd, buffer)
			if readErr != nil {
				result <- readErr
				return
			}
			for offset := 0; offset+syscall.SizeofInotifyEvent <= count; {
				nameLength := int(binary.NativeEndian.Uint32(buffer[offset+12 : offset+16]))
				eventEnd := offset + syscall.SizeofInotifyEvent + nameLength
				if eventEnd > count {
					result <- errors.New("truncated inotify event")
					return
				}
				name := strings.TrimRight(string(buffer[offset+syscall.SizeofInotifyEvent:eventEnd]), "\x00")
				if strings.HasPrefix(name, temporaryConfigurationPrefix) {
					if inject != nil {
						result <- inject(filepath.Join(directory, name))
						return
					}
					result <- nil
					return
				}
				offset = eventEnd
			}
		}
	}()
	return result
}

type treeEntry struct {
	Mode    os.FileMode
	ModTime int64
	Data    string
}

func snapshotTree(t *testing.T, root string) map[string]treeEntry {
	t.Helper()
	rootFS, err := os.OpenRoot(root)
	if err != nil {
		t.Fatalf("open root: %v", err)
	}
	t.Cleanup(func() {
		if err := rootFS.Close(); err != nil {
			t.Errorf("close root: %v", err)
		}
	})
	snapshot := make(map[string]treeEntry)
	err = filepath.WalkDir(root, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		item := treeEntry{Mode: info.Mode(), ModTime: info.ModTime().UnixNano()}
		if info.Mode().IsRegular() {
			contents, err := rootFS.ReadFile(relative)
			if err != nil {
				return err
			}
			item.Data = string(contents)
		}
		snapshot[relative] = item
		return nil
	})
	if err != nil {
		t.Fatalf("snapshot root: %v", err)
	}
	return snapshot
}

